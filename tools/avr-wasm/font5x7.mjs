export function fontBytes() {
  if (GLYPHS.length !== 95) throw new Error(`expected 95 glyphs, got ${GLYPHS.length}`);
  return GLYPHS.flatMap((line, i) => {
    if (line[0] !== String.fromCharCode(32 + i) && !(i === 0 && line[0] === ' ')) throw new Error(`glyph ${i} is '${line[0]}'`);
    const rows = line.slice(4).trim().split(/\s+/);
    if (rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error(`glyph '${line[0]}' is not 5×7`);
    return [0, 1, 2, 3, 4].map((x) => rows.reduce((b, row, y) => b | (row[x] === '#' ? 1 << y : 0), 0));
  });
}

if (process.argv[1]?.endsWith('font5x7.mjs')) {
  const bytes = fontBytes();
  const rows = [];
  for (let i = 0; i < 95; i++) rows.push(`  ${bytes.slice(i * 5, i * 5 + 5).map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')}, // ${JSON.stringify(String.fromCharCode(32 + i))}`);
  writeFileSync(new URL('./libraries/OLEDFont.h', import.meta.url), `// GENERATED by tools/avr-wasm/font5x7.mjs — our own 5×7 font, ASCII 32–126. Do not edit.
#pragma once
#include <avr/pgmspace.h>
static const unsigned char OLED_FONT[95 * 5] PROGMEM = {
${rows.join('\n')}
};
`);
  console.log('OLEDFont.h written');
}
